// 이슈 #59: Supabase 기본 권한이 옛 방식이든 새 방식이든 마이그레이션 적용 결과 권한이 같아야 한다.
//
// - 옛 방식: public의 새 테이블·시퀀스에 anon·authenticated·service_role 모두 권한을 준다(supabase-shim.sql).
// - 새 방식: 기본 권한을 주지 않는다(Supabase changelog #45329, 2026-05-30 새 프로젝트, 2026-10-30 기존 프로젝트).
// 테스트 프로젝트가 어느 쪽이든 db push 결과가 로컬 테스트와 같은지 이 파일로 확인한다.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { SUPABASE_DIR, migrationFiles } from "./helpers/db.ts";

const LEGACY_SHIM = readFileSync(join(SUPABASE_DIR, "tests", "supabase-shim.sql"), "utf8");
const TABLE_SEQUENCE_DEFAULTS =
  /^alter default privileges in schema public grant all on (tables|sequences) .*$/gm;

/** shim에서 테이블·시퀀스 기본 권한 줄만 뺀다. 함수 기본 권한은 공지에 없어 남긴다. */
function newDefaultsShim(): string {
  const removed = LEGACY_SHIM.match(TABLE_SEQUENCE_DEFAULTS) ?? [];
  // shim이 바뀌어 줄을 못 찾으면 두 DB가 같아져 이 테스트가 아무것도 확인하지 못한다.
  if (removed.length !== 2) {
    throw new Error(
      `supabase-shim.sql에서 테이블·시퀀스 기본 권한 줄 2개를 찾지 못했다: ${removed.length}개`,
    );
  }
  return LEGACY_SHIM.replace(TABLE_SEQUENCE_DEFAULTS, "");
}

async function migratedDb(shim: string): Promise<PGlite> {
  const db = new PGlite();
  await db.exec(shim);
  for (const path of migrationFiles()) {
    await db.exec(readFileSync(path, "utf8"));
  }
  return db;
}

const ROLES = `('anon', 'authenticated', 'service_role')`;

/** 세 역할이 public·private에 가진 테이블·컬럼·시퀀스 권한 (한 줄에 하나, 정렬) */
async function grants(db: PGlite): Promise<string[]> {
  const { rows } = await db.query<{ g: string }>(`
    select 'table ' || grantee || ' ' || table_schema || '.' || table_name || ' ' || privilege_type as g
    from information_schema.role_table_grants
    where grantee in ${ROLES} and table_schema in ('public', 'private')
    union all
    select 'column ' || grantee || ' ' || table_schema || '.' || table_name || '.' || column_name || ' ' || privilege_type
    from information_schema.column_privileges
    where grantee in ${ROLES} and table_schema in ('public', 'private')
    union all
    select 'sequence ' || r.rolname || ' ' || n.nspname || '.' || c.relname || ' ' || p.privilege_type
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    cross join lateral aclexplode(c.relacl) p
    join pg_roles r on r.oid = p.grantee
    where c.relkind = 'S' and n.nspname in ('public', 'private') and r.rolname in ${ROLES}
    order by 1
  `);
  return rows.map((row) => row.g);
}

let legacy: PGlite;
let current: PGlite;

beforeAll(async () => {
  [legacy, current] = await Promise.all([migratedDb(LEGACY_SHIM), migratedDb(newDefaultsShim())]);
});

afterAll(async () => {
  await Promise.all([legacy?.close(), current?.close()]);
});

describe("#59 Supabase 기본 권한과 상관없는 역할 권한", () => {
  it("옛 기본 권한과 새 기본 권한에서 anon·authenticated·service_role 권한이 같다", async () => {
    const [legacyGrants, currentGrants] = await Promise.all([grants(legacy), grants(current)]);
    expect(currentGrants.length).toBeGreaterThan(0);
    expect(currentGrants).toEqual(legacyGrants);
  });

  it("새 기본 권한에서도 service_role은 public의 모든 테이블을 읽고 쓴다", async () => {
    const { rows } = await current.query<{ table_name: string }>(`
      select c.relname as table_name
      from pg_class c
      where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
        and not (
          has_table_privilege('service_role', c.oid, 'select')
          and has_table_privilege('service_role', c.oid, 'insert')
          and has_table_privilege('service_role', c.oid, 'update')
          and has_table_privilege('service_role', c.oid, 'delete')
        )
    `);
    expect(rows).toEqual([]);
  });

  it("anon·authenticated는 public 시퀀스 권한이 없다", async () => {
    const { rows } = await legacy.query<{ g: string }>(`
      select r.rolname || ' ' || c.relname as g
      from pg_class c
      cross join lateral aclexplode(c.relacl) p
      join pg_roles r on r.oid = p.grantee
      where c.relkind = 'S' and c.relnamespace = 'public'::regnamespace
        and r.rolname in ('anon', 'authenticated')
    `);
    expect(rows).toEqual([]);
  });

  it("앞으로 만드는 public 테이블은 service_role에만 기본 권한이 간다", async () => {
    for (const db of [legacy, current]) {
      await db.transaction(async (tx) => {
        await tx.exec(
          `create table public.role_grants_probe (id integer generated by default as identity)`,
        );
        const { rows } = await tx.query<{ role: string; allowed: boolean }>(`
          select r as role, has_table_privilege(r, 'public.role_grants_probe', 'select') as allowed
          from unnest(array['anon', 'authenticated', 'service_role']) r
          order by 1
        `);
        expect(rows).toEqual([
          { role: "anon", allowed: false },
          { role: "authenticated", allowed: false },
          { role: "service_role", allowed: true },
        ]);
        await tx.rollback();
      });
    }
  });
});
