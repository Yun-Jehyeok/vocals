--     그래서 테이블마다 먼저 모두 회수하고 필요한 것만 다시 준다.
--   - 남에게 숨길 정보는 1:1 별도 테이블에 두고 행 RLS(본인·운영자)로만 막는다. 읽기에 컬럼 권한을 쓰지 않는다.
